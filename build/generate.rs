use std::collections::{BTreeMap, BTreeSet};

use serde::Deserialize;

const MANIFEST_JSON: &str = include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/crud_manifest.json"));

// ════════════════════════════════════════════════════════════════════════════
// Manifest schema
// ════════════════════════════════════════════════════════════════════════════

#[derive(Debug, Deserialize)]
pub struct Manifest {
    /// Entity kinds exposed to Python. This is the central, easy-to-modify filter.
    pub type_filter: Vec<String>,
    /// EntityCommon fields promoted to the base `Entity` class.
    #[serde(default = "default_base_fields")]
    pub base_fields: Vec<String>,
    /// Semantic/API overrides. The registry supplies types and defaults for
    /// everything else.
    #[serde(default)]
    pub overrides: BTreeMap<String, EntityOverride>,
    /// Reserved documentation area for hand-written bindings.
    #[serde(default)]
    pub manual_overrides: BTreeMap<String, String>,
}

fn default_base_fields() -> Vec<String> {
    vec!["handle".to_string(), "layer".to_string()]
}

#[derive(Debug, Deserialize, Default, Clone)]
pub struct EntityOverride {
    #[serde(default)]
    pub constructor: Option<ConstructorDef>,
    #[serde(default)]
    pub fields: BTreeMap<String, FieldOverride>,
}

#[derive(Debug, Deserialize, Clone)]
pub struct ConstructorDef {
    pub kind: String,
    #[serde(default)]
    pub args: Vec<String>,
}

#[derive(Debug, Deserialize, Default, Clone)]
pub struct FieldOverride {
    #[serde(default)]
    pub python_name: Option<String>,
    #[serde(default)]
    pub python_type: Option<String>,
    #[serde(default)]
    pub default: Option<String>,
    #[serde(default)]
    pub flatten: Option<Vec<String>>,
    #[serde(default)]
    pub rust_getter: Option<String>,
    #[serde(default)]
    pub rust_setter: Option<String>,
    #[serde(default)]
    pub exclude: bool,
}

impl Manifest {
    pub fn load() -> Self {
        serde_json::from_str(MANIFEST_JSON).expect("crud_manifest.json should be valid JSON")
    }
}

// ════════════════════════════════════════════════════════════════════════════
// Type registry schema
// ════════════════════════════════════════════════════════════════════════════

#[derive(Debug, Deserialize)]
pub struct TypeRegistry {
    pub types: BTreeMap<String, TypeInfo>,
}

#[derive(Debug, Deserialize, Clone)]
pub struct TypeInfo {
    pub name: String,
    pub kind: String,
    #[serde(default)]
    pub fields: Vec<RegistryField>,
    #[serde(default)]
    pub variants: Vec<RegistryVariant>,
}

#[derive(Debug, Deserialize, Clone)]
pub struct RegistryField {
    pub name: String,
    pub type_id: String,
    #[serde(default)]
    pub optional: bool,
    #[serde(default)]
    pub is_sequence: bool,
}

#[derive(Debug, Deserialize, Clone)]
pub struct RegistryVariant {
    pub name: String,
    pub discriminant: u32,
    #[serde(default)]
    pub fields: Vec<RegistryField>,
}

impl TypeRegistry {
    pub fn load(path: &std::path::Path) -> Self {
        let text = std::fs::read_to_string(path).unwrap_or_else(|e| {
            panic!("failed to read type registry from {}: {e}", path.display())
        });
        serde_json::from_str(&text).expect("type_registry.json should be valid JSON")
    }

    pub fn get(&self, name: &str) -> Option<&TypeInfo> {
        self.types.get(name)
    }
}

// ════════════════════════════════════════════════════════════════════════════
// Resolved field (registry + overrides)
// ════════════════════════════════════════════════════════════════════════════

#[derive(Debug, Clone)]
pub struct ResolvedField {
    pub python_name: String,
    pub python_type: String,
    pub default: String,
    pub rust_getter: String,
    pub rust_setter: String,
}

// ════════════════════════════════════════════════════════════════════════════
// Public generation entry points
// ════════════════════════════════════════════════════════════════════════════

pub fn generate_all(manifest: &Manifest, registry: &TypeRegistry) -> (String, String, String) {
    (
        generate_entities_py(manifest, registry),
        generate_entities_pyi(manifest, registry),
        generate_entity_crud(manifest, registry),
    )
}

// ════════════════════════════════════════════════════════════════════════════
// Python source generation
// ════════════════════════════════════════════════════════════════════════════

fn generate_entities_py(manifest: &Manifest, registry: &TypeRegistry) -> String {
    let mut out = String::new();
    out.push_str("# Generated by ocs_python_repl/build.rs from crud_manifest.json + type registry.\n");
    out.push_str("# Do not edit by hand.\n\n");
    out.push_str("from __future__ import annotations\n\n");
    out.push_str("from dataclasses import dataclass, field\n");
    out.push_str("from typing import Dict, List, Optional, Tuple, Union\n\n");

    for name in helper_order(manifest, registry) {
        if let Some(info) = registry.get(&name) {
            if info.kind == "Enum" && info.variants.iter().all(|v| v.fields.is_empty()) {
                continue;
            }
            out.push_str(&python_helper_class(&name, info, registry));
        }
    }

    if let Some(common) = registry.get("EntityCommon") {
        out.push_str(&python_entity_base("Entity", common, &manifest.base_fields));
    }

    for kind in &manifest.type_filter {
        if let Some(info) = registry.get(kind) {
            let fields = resolve_entity_fields(manifest, registry, kind, info);
            out.push_str(&python_dataclass(kind, &fields, true));
        }
    }
    out
}

fn generate_entities_pyi(manifest: &Manifest, registry: &TypeRegistry) -> String {
    let mut out = String::new();
    out.push_str("# Generated by ocs_python_repl/build.rs from crud_manifest.json + type registry.\n");
    out.push_str("# Do not edit by hand.\n\n");
    out.push_str("from typing import Dict, List, Optional, Tuple, Union\n\n");

    for name in helper_order(manifest, registry) {
        if let Some(info) = registry.get(&name) {
            if info.kind == "Enum" && info.variants.iter().all(|v| v.fields.is_empty()) {
                continue;
            }
            out.push_str(&python_helper_stub(&name, info, registry));
        }
    }

    if let Some(common) = registry.get("EntityCommon") {
        out.push_str(&python_entity_base_stub("Entity", common, &manifest.base_fields));
    }

    for kind in &manifest.type_filter {
        if let Some(info) = registry.get(kind) {
            let fields = resolve_entity_fields(manifest, registry, kind, info);
            out.push_str(&python_stub(kind, &fields));
        }
    }
    out
}

fn helper_order(manifest: &Manifest, registry: &TypeRegistry) -> Vec<String> {
    let mut needed: BTreeSet<String> = BTreeSet::new();
    for kind in &manifest.type_filter {
        if let Some(info) = registry.get(kind) {
            for f in &info.fields {
                if f.name == "common" {
                    continue;
                }
                collect_helper_type(registry, f, &mut needed);
            }
        }
    }

    // These types are only referenced through manifest-overridden fields
    // (e.g. vertices -> points) and have private fields or otherwise
    // unsupported shapes, so skip helper generation for them.
    let skip: BTreeSet<String> = BTreeSet::from([
        "VertexFlags".to_string(),
        "PolylineFlags".to_string(),
        "Vertex2D".to_string(),
        "Vertex3D".to_string(),
        "Vertex3DPolyline".to_string(),
        "LwVertex".to_string(),
        "SplineFlags".to_string(),
    ]);
    let needed: BTreeSet<String> = needed.difference(&skip).cloned().collect();

    let mut ordered = Vec::new();
    let mut remaining: Vec<String> = needed.into_iter().collect();
    while !remaining.is_empty() {
        let mut progress = false;
        for name in remaining.clone() {
            if let Some(info) = registry.get(&name) {
                let deps: Vec<String> = info
                    .fields
                    .iter()
                    .chain(info.variants.iter().flat_map(|v| v.fields.iter()))
                    .map(|f| f.type_id.clone())
                    .filter(|t| *t != name && remaining.contains(t))
                    .collect();
                if deps.is_empty() {
                    ordered.push(name.clone());
                    remaining.retain(|n| n != &name);
                    progress = true;
                }
            } else {
                ordered.push(name.clone());
                remaining.retain(|n| n != &name);
                progress = true;
            }
        }
        if !progress && !remaining.is_empty() {
            ordered.append(&mut remaining);
        }
    }
    ordered
}

fn collect_helper_type(registry: &TypeRegistry, field: &RegistryField, out: &mut BTreeSet<String>) {
    let name = field.type_id.clone();
    if is_builtin(&name) || name == "Vector3" || name == "Vector2" || name == "Handle" {
        return;
    }
    if let Some(info) = registry.get(&name) {
        if out.insert(name.clone()) {
            for f in &info.fields {
                collect_helper_type(registry, f, out);
            }
            for v in &info.variants {
                for f in &v.fields {
                    collect_helper_type(registry, f, out);
                }
            }
        }
    }
}

fn python_helper_class(name: &str, info: &TypeInfo, registry: &TypeRegistry) -> String {
    let mut out = String::new();
    out.push_str("@dataclass\n");
    out.push_str(&format!("class {name}:\n"));
    if info.kind == "Enum" {
        let default_kind = info
            .variants
            .first()
            .map(|v| v.name.clone())
            .unwrap_or_default();
        out.push_str(&format!("    kind: str = \"{default_kind}\"\n"));
    }
    let fields: Vec<(String, &RegistryField)> = if info.kind == "Struct" {
        info.fields.iter().map(|f| (f.name.clone(), f)).collect()
    } else {
        let mut map: BTreeMap<String, &RegistryField> = BTreeMap::new();
        for v in &info.variants {
            for f in &v.fields {
                let py_name = enum_field_python_name(&v.name, &f.name);
                map.entry(py_name).or_insert(f);
            }
        }
        map.into_iter().collect()
    };
    if fields.is_empty() && info.kind != "Enum" {
        out.push_str("    pass\n\n");
        return out;
    }
    for (py_name, f) in fields {
        let (py_type, default) = python_type_and_default(registry, f);
        out.push_str(&format!("    {py_name}: {py_type} = {default}\n"));
    }
    out.push('\n');
    out
}

fn python_helper_stub(name: &str, info: &TypeInfo, registry: &TypeRegistry) -> String {
    let mut out = String::new();
    out.push_str(&format!("class {name}:\n"));
    if info.kind == "Enum" {
        out.push_str("    kind: str\n");
    }
    let fields: Vec<(String, &RegistryField)> = if info.kind == "Struct" {
        info.fields.iter().map(|f| (f.name.clone(), f)).collect()
    } else {
        let mut map: BTreeMap<String, &RegistryField> = BTreeMap::new();
        for v in &info.variants {
            for f in &v.fields {
                let py_name = enum_field_python_name(&v.name, &f.name);
                map.entry(py_name).or_insert(f);
            }
        }
        map.into_iter().collect()
    };
    if fields.is_empty() && info.kind != "Enum" {
        out.push_str("    ...\n\n");
        return out;
    }
    for (py_name, f) in fields {
        let (py_type, _) = python_type_and_default(registry, f);
        out.push_str(&format!("    {py_name}: {py_type}\n"));
    }
    out.push('\n');
    out
}

fn python_entity_base(name: &str, info: &TypeInfo, base_fields: &[String]) -> String {
    let mut out = String::new();
    out.push_str("@dataclass\n");
    out.push_str(&format!("class {name}:\n"));
    for field_name in base_fields {
        if let Some(f) = info.fields.iter().find(|f| &f.name == field_name) {
            let (py_type, default) = python_type_and_default(registry_dummy(), f);
            out.push_str(&format!("    {field_name}: {py_type} = {default}\n"));
        }
    }
    out.push('\n');
    out
}

fn python_entity_base_stub(name: &str, info: &TypeInfo, base_fields: &[String]) -> String {
    let mut out = String::new();
    out.push_str(&format!("class {name}:\n"));
    for field_name in base_fields {
        if let Some(f) = info.fields.iter().find(|f| &f.name == field_name) {
            let (py_type, _) = python_type_and_default(registry_dummy(), f);
            out.push_str(&format!("    {field_name}: {py_type}\n"));
        }
    }
    out.push('\n');
    out
}

fn python_dataclass(name: &str, fields: &[ResolvedField], inherit_entity: bool) -> String {
    let mut out = String::new();
    out.push_str("@dataclass\n");
    out.push_str(&format!(
        "class {name}({}):\n",
        if inherit_entity { "Entity" } else { "object" }
    ));
    if fields.is_empty() {
        out.push_str("    pass\n\n");
        return out;
    }
    for f in fields {
        out.push_str(&format!(
            "    {name}: {type_} = {default}\n",
            name = f.python_name,
            type_ = f.python_type,
            default = f.default
        ));
    }
    out.push('\n');
    out
}

fn python_stub(name: &str, fields: &[ResolvedField]) -> String {
    let mut out = String::new();
    out.push_str(&format!("class {name}:\n"));
    if fields.is_empty() {
        out.push_str("    ...\n\n");
        return out;
    }
    for f in fields {
        out.push_str(&format!(
            "    {name}: {type_}\n",
            name = f.python_name,
            type_ = f.python_type
        ));
    }
    out.push('\n');
    out
}

fn registry_dummy() -> &'static TypeRegistry {
    // Only used for EntityCommon base fields where we know the types already.
    static REG: std::sync::OnceLock<TypeRegistry> = std::sync::OnceLock::new();
    REG.get_or_init(|| TypeRegistry {
        types: BTreeMap::new(),
    })
}

// ════════════════════════════════════════════════════════════════════════════
// Rust CRUD generation
// ════════════════════════════════════════════════════════════════════════════

fn generate_entity_crud(manifest: &Manifest, registry: &TypeRegistry) -> String {
    let mut out = String::new();
    out.push_str("// Generated by ocs_python_repl/build.rs from crud_manifest.json + type registry.\n");
    out.push_str("// Do not edit by hand.\n\n");

    for name in helper_order(manifest, registry) {
        if let Some(info) = registry.get(&name) {
            if info.kind == "Enum" && info.variants.iter().all(|v| v.fields.is_empty()) {
                out.push_str(&unit_enum_name_fn(&name, info));
                out.push('\n');
                out.push_str(&unit_enum_parse_fn(&name, info));
                out.push('\n');
            } else {
                out.push_str(&helper_to_py(&name, info, registry));
                out.push('\n');
                out.push_str(&py_to_helper(&name, info, registry));
                out.push('\n');
            }
        }
    }

    out.push_str(&generate_entity_to_py(manifest, registry));
    out.push('\n');
    out.push_str(&generate_py_to_entity(manifest, registry));
    out
}

fn unit_enum_name_fn(name: &str, info: &TypeInfo) -> String {
    let mut arms = String::new();
    for v in &info.variants {
        arms.push_str(&format!(
            "        {path}::{v} => \"{v}\",\n",
            path = rust_type_path(name),
            v = v.name
        ));
    }
    format!(
        r#"fn {snake}_name(value: &{path}) -> &'static str {{
    match value {{
{arms}    }}
}}
"#,
        snake = snake_case(name),
        path = rust_type_path(name),
        arms = arms
    )
}

fn unit_enum_parse_fn(name: &str, info: &TypeInfo) -> String {
    let mut arms = String::new();
    for v in &info.variants {
        arms.push_str(&format!(
            "        \"{v}\" => Ok({path}::{v}),\n",
            path = rust_type_path(name),
            v = v.name
        ));
    }
    format!(
        r#"fn parse_{snake}_value(value: &Bound<'_, PyAny>) -> PyResult<{path}> {{
    let kind = value.extract::<String>()?;
    match kind.as_str() {{
{arms}
        _ => Err(PyErr::new::<pyo3::exceptions::PyValueError, _>(format!("unsupported {name} kind: {{}}", kind))),
    }}
}}

fn parse_{snake}(entity: &Bound<'_, PyAny>, key: &str) -> PyResult<{path}> {{
    let value = entity_attr(entity, key).ok_or_else(|| PyErr::new::<pyo3::exceptions::PyValueError, _>(format!("missing {{}}", key)))?;
    parse_{snake}_value(&value)
}}
"#,
        snake = snake_case(name),
        path = rust_type_path(name),
        name = name,
        arms = arms
    )
}

fn is_numeric_field_name(name: &str) -> bool {
    !name.is_empty() && name.chars().all(|c| c.is_ascii_digit())
}

fn enum_field_python_name(variant_name: &str, field_name: &str) -> String {
    if is_numeric_field_name(field_name) {
        snake_case(variant_name)
    } else {
        field_name.to_string()
    }
}

fn is_tuple_variant(fields: &[RegistryField]) -> bool {
    fields.iter().all(|f| is_numeric_field_name(&f.name))
}

fn helper_to_py(name: &str, info: &TypeInfo, registry: &TypeRegistry) -> String {
    let mut body = String::new();
    if info.kind == "Struct" {
        for f in &info.fields {
            let getter = rust_getter(registry, "value", &f.name, &f.type_id, f.optional, f.is_sequence);
            body.push_str(&format!(
                "    kwargs.set_item(\"{}\", {})?;\n",
                f.name, getter
            ));
        }
    } else if info.kind == "Enum" {
        body.push_str("    match value {\n");
        for v in &info.variants {
            let bindings: Vec<(String, String, String)> = v
                .fields
                .iter()
                .enumerate()
                .map(|(i, f)| {
                    (
                        enum_field_python_name(&v.name, &f.name),
                        f.type_id.clone(),
                        format!("f{}", i),
                    )
                })
                .collect();
            let pat = if v.fields.is_empty() {
                format!("{}::{}", rust_type_path(name), v.name)
            } else if is_tuple_variant(&v.fields) {
                let args: Vec<String> = bindings.iter().map(|(_, _, b)| b.clone()).collect();
                format!("{}::{}({})", rust_type_path(name), v.name, args.join(", "))
            } else {
                let args: Vec<String> = v
                    .fields
                    .iter()
                    .enumerate()
                    .map(|(i, f)| format!("{}: f{}", f.name, i))
                    .collect();
                format!("{}::{} {{ {} }}", rust_type_path(name), v.name, args.join(", "))
            };
            body.push_str(&format!("        {pat} => {{\n"));
            body.push_str(&format!(
                "            kwargs.set_item(\"kind\", \"{}\")?;\n",
                v.name
            ));
            for (py_name, ftype, binding) in bindings {
                let getter = rust_value_getter_ref(registry, &binding, &ftype);
                body.push_str(&format!(
                    "            kwargs.set_item(\"{}\", {})?;\n",
                    py_name, getter
                ));
            }
            body.push_str("        }\n");
        }
        body.push_str("    }\n");
    }

    format!(
        r#"fn {snake}_to_py(py: Python<'_>, value: &{path}) -> PyResult<PyObject> {{
    let entities = py.import("ocs.entities")?;
    let cls = entities.getattr("{name}")?;
    let kwargs = PyDict::new(py);
{body}    Ok(cls.call((), Some(&kwargs))?.into())
}}
"#,
        snake = snake_case(name),
        path = rust_type_path(name),
        name = name,
        body = body
    )
}

fn py_to_helper(name: &str, info: &TypeInfo, registry: &TypeRegistry) -> String {
    let mut body = String::new();
    if info.kind == "Struct" {
        body.push_str(&format!("    Ok({} {{\n", rust_type_path(name)));
        for f in &info.fields {
            let setter = rust_setter_expr(registry, "obj", &f.name, &f.type_id, f.optional, f.is_sequence);
            body.push_str(&format!("        {}: {setter},\n", f.name));
        }
        body.push_str("    })\n");
    } else if info.kind == "Enum" {
        body.push_str("    let kind = get_opt_string(obj, \"kind\")?;\n");
        body.push_str("    match kind.as_str() {\n");
        for v in &info.variants {
            body.push_str(&format!("        \"{}\" => {{\n", v.name));
            if v.fields.is_empty() {
                body.push_str(&format!(
                    "            Ok({}::{})\n",
                    rust_type_path(name),
                    v.name
                ));
            } else if is_tuple_variant(&v.fields) {
                let mut args = Vec::new();
                for f in &v.fields {
                    let py_name = enum_field_python_name(&v.name, &f.name);
                    let setter = rust_setter_expr(registry, "obj", &py_name, &f.type_id, f.optional, f.is_sequence);
                    args.push(setter);
                }
                body.push_str(&format!(
                    "            Ok({}::{}({}))\n",
                    rust_type_path(name),
                    v.name,
                    args.join(", ")
                ));
            } else {
                let mut fields = Vec::new();
                for f in &v.fields {
                    let py_name = enum_field_python_name(&v.name, &f.name);
                    let setter = rust_setter_expr(registry, "obj", &py_name, &f.type_id, f.optional, f.is_sequence);
                    fields.push(format!("{}: {setter}", f.name));
                }
                body.push_str(&format!(
                    "            Ok({}::{} {{ {} }})\n",
                    rust_type_path(name),
                    v.name,
                    fields.join(", ")
                ));
            }
            body.push_str("        }\n");
        }
        body.push_str(&format!(
            "        _ => Err(PyErr::new::<pyo3::exceptions::PyValueError, _>(format!(\"unsupported {name} kind: {{}}\", kind))),\n"
        ));
        body.push_str("    }\n");
    }

    format!(
        r#"fn py_to_{snake}(obj: &Bound<'_, PyAny>) -> PyResult<{path}> {{
{body}}}
"#,
        snake = snake_case(name),
        path = rust_type_path(name),
        body = body
    )
}

fn generate_entity_to_py(manifest: &Manifest, registry: &TypeRegistry) -> String {
    let mut arms = String::new();
    for kind in &manifest.type_filter {
        let Some(info) = registry.get(kind) else { continue };
        let var = entity_var(kind);
        let fields = resolve_entity_fields(manifest, registry, kind, info);
        arms.push_str(&format!(
            "        EntityType::{kind}({var}) => (\"{kind}\", {{\n            let dict = base_kwargs(py, {var}.common.layer.clone())?;\n"
        ));
        for f in &fields {
            arms.push_str(&format!(
                "            dict.set_item(\"{}\", {})?;\n",
                f.python_name, f.rust_getter
            ));
        }
        arms.push_str("            dict\n        }),\n");
    }

    format!(
        r#"pub fn entity_to_py(
    py: Python<'_>,
    entity: &acadrust::EntityType,
    handle: u64,
) -> PyResult<PyObject> {{
    let entities = py.import("ocs.entities")?;
    let (kind, kwargs): (&str, Bound<'_, PyDict>) = match entity {{
{arms}
        other => ("Entity", base_kwargs(py, other.common().layer.clone())?),
    }};
    let cls = entities.getattr(kind)?;
    let obj = cls.call((), Some(&kwargs))?;
    obj.setattr("handle", handle)?;
    Ok(obj.into())
}}
"#,
        arms = arms
    )
}

fn generate_py_to_entity(manifest: &Manifest, registry: &TypeRegistry) -> String {
    let mut arms = String::new();
    for kind in &manifest.type_filter {
        let Some(info) = registry.get(kind) else { continue };
        let def = manifest.overrides.get(kind);
        let var = entity_var(kind);
        let constructor = rust_constructor(kind, def);
        let fields = resolve_entity_fields(manifest, registry, kind, info);
        let mut setters = String::new();
        for f in &fields {
            for line in f.rust_setter.lines() {
                setters.push_str(&format!("            {line}\n"));
            }
        }
        arms.push_str(&format!(
            "        \"{kind}\" => {{\n            let mut {var} = {constructor};\n            set_common(&mut {var}, entity)?;\n{setters}\n            acadrust::EntityType::{kind}({var})\n        }}\n"
        ));
    }

    format!(
        r#"pub fn py_to_entity(
    entity: &Bound<'_, PyAny>,
) -> PyResult<acadrust::EntityType> {{
    let kind = entity_kind(entity)?;
    Ok(match kind.as_str() {{
{arms}
        _ => {{
            return Err(pyo3::exceptions::PyValueError::new_err(format!(
                "unsupported entity kind: {{}}",
                kind
            )));
        }}
    }})
}}
"#,
        arms = arms
    )
}

// ════════════════════════════════════════════════════════════════════════════
// Field resolution
// ════════════════════════════════════════════════════════════════════════════

fn resolve_entity_fields(
    manifest: &Manifest,
    registry: &TypeRegistry,
    kind: &str,
    info: &TypeInfo,
) -> Vec<ResolvedField> {
    let override_def = manifest.overrides.get(kind).cloned().unwrap_or_default();
    let var = entity_var(kind);
    let mut resolved = Vec::new();

    for field in &info.fields {
        if field.name == "common" {
            continue;
        }
        let field_override = override_def
            .fields
            .get(&field.name)
            .cloned()
            .unwrap_or_default();
        if field_override.exclude {
            continue;
        }

        // Flatten a struct field into multiple Python fields.
        if let Some(flatten) = &field_override.flatten {
            let inner = &field.type_id;
            if let Some(inner_info) = registry.get(inner) {
                let flat_defaults = parse_flatten_default(field_override.default.as_deref());
                for (idx, py_name) in flatten.iter().enumerate() {
                    let inner_field = inner_info.fields.get(idx).unwrap_or_else(|| {
                        panic!("{kind}.{} flatten index {idx} out of range", field.name)
                    });
                    let (py_type, type_default) = python_type_and_default(registry, inner_field);
                    let default = flat_defaults
                        .get(idx)
                        .cloned()
                        .unwrap_or(type_default);
                    let rust_path = format!("{}.{}.{}", var, field.name, inner_field.name);
                    let getter = field_override.rust_getter.clone().unwrap_or(rust_path.clone());
                    let rust_default = rust_default_literal(&default, &inner_field.type_id);
                    let setter = field_override.rust_setter.clone().unwrap_or_else(|| {
                        format!("{rust_path} = get_opt_{}(entity, \"{py_name}\", {rust_default});",
                            rust_primitive_getter(&inner_field.type_id),
                            py_name = py_name,
                            rust_default = rust_default
                        )
                    });
                    resolved.push(ResolvedField {
                        python_name: py_name.clone(),
                        python_type: py_type,
                        default,
                        rust_getter: getter,
                        rust_setter: setter,
                    });
                }
            }
            continue;
        }

        let python_name = field_override
            .python_name
            .clone()
            .unwrap_or_else(|| field.name.clone());
        let (py_type, default) = python_type_and_default(registry, field);
        let python_type = field_override.python_type.clone().unwrap_or(py_type);
        let default = field_override.default.clone().unwrap_or(default);
        let default = normalize_default(&python_type, &default);

        let rust_getter = field_override.rust_getter.clone().unwrap_or_else(|| {
            rust_getter(registry, var, &field.name, &field.type_id, field.optional, field.is_sequence)
        });
        let rust_setter = field_override.rust_setter.clone().unwrap_or_else(|| {
            format!(
                "{}.{name} = {expr};",
                var,
                name = field.name,
                expr = rust_setter_expr(registry, "entity", &python_name, &field.type_id, field.optional, field.is_sequence)
            )
        });
        resolved.push(ResolvedField {
            python_name,
            python_type,
            default,
            rust_getter,
            rust_setter,
        });
    }
    resolved
}

fn rust_default_literal(py_default: &str, type_id: &str) -> String {
    match type_id {
        "bool" => match py_default {
            "True" => "true".to_string(),
            "False" => "false".to_string(),
            _ => py_default.to_string(),
        },
        _ => py_default.to_string(),
    }
}

fn parse_flatten_default(default: Option<&str>) -> Vec<String> {
    let Some(d) = default else { return Vec::new() };
    let inner = d.trim();
    if inner.starts_with('(') && inner.ends_with(')') {
        inner[1..inner.len() - 1]
            .split(',')
            .map(|s| s.trim().to_string())
            .collect()
    } else {
        Vec::new()
    }
}

fn normalize_default(python_type: &str, default: &str) -> String {
    if python_type.starts_with("List[") && default == "[]" {
        "field(default_factory=list)".to_string()
    } else {
        default.to_string()
    }
}

// ════════════════════════════════════════════════════════════════════════════
// Type mapping
// ════════════════════════════════════════════════════════════════════════════

fn python_type_and_default(registry: &TypeRegistry, field: &RegistryField) -> (String, String) {
    let inner = inner_python_type(registry, &field.type_id);
    let mut py_type = inner.clone();
    let mut default = default_for_python_type(&inner);

    if field.is_sequence {
        py_type = format!("List[{inner}]");
        default = "field(default_factory=list)".to_string();
    }
    if field.optional {
        py_type = format!("Optional[{py_type}]");
        default = "None".to_string();
    }
    (py_type, default)
}

fn inner_python_type(registry: &TypeRegistry, type_id: &str) -> String {
    match type_id {
        "f64" | "f32" => "float".to_string(),
        "i8" | "i16" | "i32" | "i64" | "u8" | "u16" | "u32" | "u64" => "int".to_string(),
        "bool" => "bool".to_string(),
        "String" | "str" => "str".to_string(),
        "Vector3" => "Tuple[float, float, float]".to_string(),
        "Vector2" => "Tuple[float, float]".to_string(),
        "Handle" => "int".to_string(),
        _ => {
            if let Some(info) = registry.get(type_id) {
                if info.kind == "Enum" && info.variants.iter().all(|v| v.fields.is_empty()) {
                    return "str".to_string();
                }
            }
            type_id.to_string()
        }
    }
}

fn default_for_python_type(py_type: &str) -> String {
    match py_type {
        "float" => "0.0".to_string(),
        "int" => "0".to_string(),
        "bool" => "False".to_string(),
        "str" => "\"\"".to_string(),
        "Tuple[float, float, float]" => "(0.0, 0.0, 0.0)".to_string(),
        "Tuple[float, float]" => "(0.0, 0.0)".to_string(),
        t if t.starts_with("Optional[") => "None".to_string(),
        t if t.starts_with("List[") => "field(default_factory=list)".to_string(),
        _ => format!("field(default_factory={py_type})"),
    }
}

fn rust_getter(
    registry: &TypeRegistry,
    var: &str,
    field_name: &str,
    type_id: &str,
    optional: bool,
    is_sequence: bool,
) -> String {
    if optional && is_sequence {
        format!(
            "{var}.{field_name}.as_ref().map(|v| v.iter().map(|item| {}).collect::<Vec<_>>())",
            rust_value_getter_ref(registry, "item", type_id)
        )
    } else if optional {
        rust_optional_getter(registry, var, field_name, type_id)
    } else if is_sequence {
        rust_sequence_getter(registry, var, field_name, type_id)
    } else {
        rust_value_getter_owned(registry, &format!("{var}.{field_name}"), type_id)
    }
}

/// Generate code that converts an owned value of `type_id` into a Python value.
/// `expr` is an expression of type `T` (not `&T`).
fn rust_value_getter_owned(registry: &TypeRegistry, expr: &str, type_id: &str) -> String {
    match type_id {
        "Vector3" => format!("v3_tuple(&({expr}))"),
        "Vector2" => format!("({expr}.x, {expr}.y)"),
        "Handle" => format!("{expr}.value()"),
        "String" | "str" => format!("{expr}.clone()"),
        _ => {
            if let Some(info) = registry.get(type_id) {
                if info.kind == "Enum" && info.variants.iter().all(|v| v.fields.is_empty()) {
                    return format!("{}_name(&({expr}))", snake_case(type_id));
                }
                if info.kind == "Enum" || info.kind == "Struct" {
                    return format!("{}_to_py(py, &({expr}))?", snake_case(type_id));
                }
            }
            expr.to_string()
        }
    }
}

/// Generate code that converts a borrowed value into a Python value.
/// `var` is an identifier already bound to `&T`.
fn rust_value_getter_ref(registry: &TypeRegistry, var: &str, type_id: &str) -> String {
    match type_id {
        "Vector3" => format!("v3_tuple({var})"),
        "Vector2" => format!("({var}.x, {var}.y)"),
        "Handle" => format!("{var}.value()"),
        "String" | "str" => format!("{var}.clone()"),
        _ => {
            if let Some(info) = registry.get(type_id) {
                if info.kind == "Enum" && info.variants.iter().all(|v| v.fields.is_empty()) {
                    return format!("{}_name({var})", snake_case(type_id));
                }
                if info.kind == "Enum" || info.kind == "Struct" {
                    return format!("{}_to_py(py, {var})?", snake_case(type_id));
                }
            }
            var.to_string()
        }
    }
}

fn rust_sequence_getter(
    registry: &TypeRegistry,
    var: &str,
    field_name: &str,
    type_id: &str,
) -> String {
    let expr = format!("{var}.{field_name}");
    match type_id {
        "f64" | "f32" | "i8" | "i16" | "i32" | "i64" | "u8" | "u16" | "u32" | "u64" | "bool" => {
            format!("{expr}.to_vec()")
        }
        "String" | "str" => format!("{expr}.clone()") ,
        "Vector3" => format!("{expr}.iter().map(v3_tuple).collect::<Vec<_>>()") ,
        "Vector2" => format!("{expr}.iter().map(|v| (v.x, v.y)).collect::<Vec<_>>()") ,
        _ => {
            if let Some(info) = registry.get(type_id) {
                if info.kind == "Enum" && info.variants.iter().all(|v| v.fields.is_empty()) {
                    return format!(
                        "{expr}.iter().map(|v| {}_name(v)).collect::<Vec<_>>()",
                        snake_case(type_id)
                    );
                }
                if info.kind == "Enum" || info.kind == "Struct" {
                    return format!(
                        "{expr}.iter().map(|v| {}_to_py(py, v)?).collect::<PyResult<Vec<_>>>()?",
                        snake_case(type_id)
                    );
                }
            }
            format!("{expr}.to_vec()")
        }
    }
}

fn rust_optional_getter(
    registry: &TypeRegistry,
    var: &str,
    field_name: &str,
    type_id: &str,
) -> String {
    let expr = format!("{var}.{field_name}");
    match type_id {
        "f64" | "f32" | "i8" | "i16" | "i32" | "i64" | "u8" | "u16" | "u32" | "u64" | "bool" => {
            expr
        }
        "String" | "str" => format!("{expr}.clone()"),
        "Vector3" => format!("{expr}.as_ref().map(v3_tuple)"),
        "Vector2" => format!("{expr}.as_ref().map(|v| (v.x, v.y))"),
        _ => {
            if let Some(info) = registry.get(type_id) {
                if info.kind == "Enum" && info.variants.iter().all(|v| v.fields.is_empty()) {
                    return format!(
                        "{expr}.as_ref().map(|v| {}_name(v))",
                        snake_case(type_id)
                    );
                }
                if info.kind == "Enum" || info.kind == "Struct" {
                    return format!(
                        "{expr}.as_ref().map(|v| {}_to_py(py, v)?)",
                        snake_case(type_id)
                    );
                }
            }
            expr
        }
    }
}

fn rust_setter_expr(
    registry: &TypeRegistry,
    entity_var: &str,
    py_name: &str,
    type_id: &str,
    optional: bool,
    is_sequence: bool,
) -> String {
    if optional && is_sequence {
        let inner = rust_setter_value_result(registry, "item", type_id);
        return format!(
            "opt_entity_attr({entity_var}, \"{py_name}\").map(|v| {{ let list = v.downcast::<PyList>()?; list.iter().map(|item| {inner}).collect::<PyResult<Vec<_>>>() }}).transpose()?"
        );
    }
    if optional {
        return rust_setter_optional_single(registry, entity_var, py_name, type_id);
    }
    if is_sequence {
        let inner = rust_setter_sequence(registry, entity_var, py_name, type_id);
        return format!(
            "if let Some(list) = entity_attr({entity_var}, \"{py_name}\") {{ {inner} }} else {{ Vec::new() }}"
        );
    }
    rust_setter_single(registry, entity_var, py_name, type_id)
}

fn rust_setter_sequence(
    registry: &TypeRegistry,
    _entity_var: &str,
    _py_name: &str,
    type_id: &str,
) -> String {
    match type_id {
        "Vector3" => "point_list(&list)?".to_string(),
        "Vector2" => "point_list_2d(&list)?".to_string(),
        _ if is_builtin(type_id) => "f64_list(&list)?".to_string(),
        _ => {
            let inner = rust_setter_value_result(registry, "item", type_id);
            format!("list.downcast::<PyList>()?.iter().map(|item| {inner}).collect::<PyResult<Vec<_>>>()?")
        }
    }
}

fn rust_setter_optional_single(
    registry: &TypeRegistry,
    entity_var: &str,
    py_name: &str,
    type_id: &str,
) -> String {
    let inner = rust_setter_value_result(registry, "v", type_id);
    format!(
        "opt_entity_attr({entity_var}, \"{py_name}\").map(|v| {inner}).transpose()?"
    )
}

fn rust_setter_single(
    registry: &TypeRegistry,
    entity_var: &str,
    py_name: &str,
    type_id: &str,
) -> String {
    match type_id {
        "Vector3" => format!(
            "py_vector3_opt({entity_var}, \"{py_name}\", acadrust::types::Vector3::default())?"
        ),
        "Vector2" => format!(
            "py_vector2_opt({entity_var}, \"{py_name}\", acadrust::types::Vector2::default())?"
        ),
        "Handle" => format!("acadrust::Handle::new(get_opt_u64({entity_var}, \"{py_name}\", 0))"),
        "String" | "str" => format!("get_opt_string({entity_var}, \"{py_name}\")?"),
        "f64" | "f32" => format!("get_opt_f64({entity_var}, \"{py_name}\", 0.0)"),
        "i8" | "i16" | "i32" => format!("get_opt_u64({entity_var}, \"{py_name}\", 0) as {type_id}"),
        "u8" | "u16" | "u32" | "u64" => format!("get_opt_u64({entity_var}, \"{py_name}\", 0) as {type_id}"),
        "bool" => format!("get_opt_bool({entity_var}, \"{py_name}\", false)"),
        _ => {
            if let Some(info) = registry.get(type_id) {
                if info.kind == "Enum" && info.variants.iter().all(|v| v.fields.is_empty()) {
                    return format!("parse_{}({entity_var}, \"{py_name}\")?", snake_case(type_id));
                }
                let snake = snake_case(type_id);
                return format!("py_to_{snake}(&entity_attr({entity_var}, \"{py_name}\").ok_or_else(|| PyErr::new::<pyo3::exceptions::PyValueError, _>(\"missing {py_name}\"))?)?");
            }
            format!("get_opt_string({entity_var}, \"{py_name}\")?")
        }
    }
}

/// Returns a `PyResult<T>` expression without the trailing `?`.
/// Used in `map(...).transpose()?` contexts.
fn rust_setter_value_result(registry: &TypeRegistry, var: &str, type_id: &str) -> String {
    match type_id {
        "Vector3" => format!("py_vector3(&{var})"),
        "Vector2" => format!("py_vector2(&{var})"),
        "f64" | "f32" => format!("{var}.extract::<f64>()"),
        "i8" | "i16" | "i32" => format!("{var}.extract::<i32>()"),
        "u8" | "u16" | "u32" | "u64" => format!("{var}.extract::<u64>()? as {type_id}"),
        "bool" => format!("{var}.extract::<bool>()"),
        "String" | "str" => format!("{var}.extract::<String>()"),
        _ => {
            if let Some(info) = registry.get(type_id) {
                if info.kind == "Enum" && info.variants.iter().all(|v| v.fields.is_empty()) {
                    return format!("parse_{}_value(&{var})", snake_case(type_id));
                }
                let snake = snake_case(type_id);
                return format!("py_to_{snake}(&{var})");
            }
            format!("{var}.extract::<String>()")
        }
    }
}

fn rust_primitive_getter(type_id: &str) -> &'static str {
    match type_id {
        "f64" | "f32" => "f64",
        "i8" | "i16" | "i32" | "i64" | "u8" | "u16" | "u32" | "u64" => "u64",
        "bool" => "bool",
        _ => "f64",
    }
}

fn rust_constructor(kind: &str, def: Option<&EntityOverride>) -> String {
    let ctor = def.and_then(|d| d.constructor.as_ref());
    let ty = format!("acadrust::entities::{kind}");
    match ctor {
        Some(c) => match c.kind.as_str() {
            "from_coords" => {
                let args = c
                    .args
                    .iter()
                    .map(|a| format!("get_opt_f64(entity, \"{}\", 0.0)", a))
                    .collect::<Vec<_>>()
                    .join(", ");
                format!("{ty}::from_coords({args})")
            }
            "new" => format!("{ty}::new()"),
            "default" => format!("{ty}::default()"),
            other => panic!("unsupported constructor kind '{other}' for {kind}"),
        },
        None => format!("{ty}::default()"),
    }
}

fn entity_var(kind: &str) -> &'static str {
    match kind {
        "Point" => "p",
        "Line" => "l",
        "Circle" => "c",
        "Arc" => "a",
        "Ellipse" => "e",
        "Polyline" | "Polyline2D" | "Polyline3D" | "LwPolyline" => "p",
        "Spline" => "s",
        "MText" => "t",
        _ => "e",
    }
}

fn rust_type_path(name: &str) -> String {
    match name {
        "Vector3" | "Vector2" => format!("acadrust::types::{name}"),
        "Handle" | "Color" | "Layer" => format!("acadrust::{name}"),
        "XDataValue" => format!("acadrust::xdata::{name}"),
        _ => format!("acadrust::entities::{name}"),
    }
}

fn snake_case(name: &str) -> String {
    let mut out = String::new();
    for (i, ch) in name.chars().enumerate() {
        if ch.is_uppercase() && i > 0 {
            out.push('_');
        }
        out.push(ch.to_ascii_lowercase());
    }
    out
}

fn is_builtin(type_id: &str) -> bool {
    matches!(
        type_id,
        "f64" | "f32" | "i8" | "i16" | "i32" | "i64" | "u8" | "u16" | "u32" | "u64" | "bool"
            | "String" | "str" | "()"
    )
}
